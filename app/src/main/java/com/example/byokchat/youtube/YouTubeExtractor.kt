package com.example.byokchat.youtube

import com.example.byokchat.ai.Http
import com.example.byokchat.tools.ToolException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.RequestBody.Companion.toRequestBody
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.downloader.Downloader
import org.schabi.newpipe.extractor.downloader.Request as ExtractorRequest
import org.schabi.newpipe.extractor.downloader.Response as ExtractorResponse
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.StreamExtractor
import org.schabi.newpipe.extractor.stream.VideoStream
import org.schabi.newpipe.extractor.MediaFormat
import java.io.IOException
import java.io.OutputStream

/**
 * NewPipeExtractor adapter (YouTube tools, 2026-11-13).
 * The extractor is used ONLY for what the official API cannot give:
 * subtitles, audio streams and video streams / downloads. It is NEVER
 * used to search (that would abuse it instead of the API).
 *
 * Known limits, stated plainly instead of hidden behind a fallback:
 * - Some videos ask YouTube for a bot check (po_token). This build has no
 *   WebView po_token provider yet, so those videos fail with a clear
 *   message instead of silently falling back to something else.
 * - Auto-translated subtitle tracks are not returned by the extractor
 *   (its source has an unused TODO for translationLanguages), so they
 *   are not offered at all.
 */

/** OkHttp-backed Downloader for the extractor (page fetches are small text). */
class OkHttpDownloader : Downloader() {
    override fun execute(request: ExtractorRequest): ExtractorResponse {
        val builder = okhttp3.Request.Builder().url(request.url())
        request.headers().forEach { (name, values) ->
            values.forEach { builder.addHeader(name, it) }
        }
        val body = request.dataToSend()?.toRequestBody(null)
        builder.method(request.httpMethod(), body)
        val call = Http.client.newCall(builder.build())
        call.execute().use { resp ->
            val text = resp.body?.string().orEmpty()
            val headers = resp.headers.toMultimap()
            val latest = resp.request.url.toString()
            return ExtractorResponse(resp.code, resp.message, headers, text, latest)
        }
    }
}

data class ResolvedStreams(
    val videoId: String,
    val title: String,
    val durationSeconds: Long,
    val audioStreams: List<AudioStream>,
    val videoStreams: List<VideoStream>,
    val subtitles: List<SubtitleTrack>,
)

object YouTubeExtractor {
    private val initLock = Any()

    @Volatile
    private var initialized = false

    fun ensureInitialized() {
        if (initialized) return
        synchronized(initLock) {
            if (!initialized) {
                NewPipe.init(OkHttpDownloader())
                initialized = true
            }
        }
    }

    /** Fetch a video's streams + subtitles. Blocking extractor calls run on IO. */
    suspend fun fetch(videoId: String): ResolvedStreams = withContext(Dispatchers.IO) {
        ensureInitialized()
        val url = "https://www.youtube.com/watch?v=$videoId"
        try {
            val extractor: StreamExtractor = NewPipe.getServiceByUrl(url).getStreamExtractor(url)
            extractor.fetchPage()
            val subtitles = runCatching { extractor.getSubtitles(MediaFormat.VTT) }.getOrDefault(emptyList())
                .filter { it.isUrl }
                .map {
                    SubtitleTrack(
                        languageTag = it.languageTag,
                        isAutoGenerated = it.isAutoGenerated,
                        displayLanguageName = it.displayLanguageName,
                        contentUrl = it.content,
                    )
                }
            ResolvedStreams(
                videoId = videoId,
                title = runCatching { extractor.name }.getOrNull().orEmpty(),
                durationSeconds = runCatching { extractor.length }.getOrDefault(0),
                audioStreams = runCatching { extractor.audioStreams }.getOrDefault(emptyList()),
                videoStreams = runCatching { extractor.videoStreams }.getOrDefault(emptyList()),
                subtitles = subtitles,
            )
        } catch (e: Exception) {
            throw ToolException(mapExtractorError(e))
        }
    }

    fun mapExtractorError(e: Exception): String {
        val msg = e.message.orEmpty()
        return when {
            msg.contains("bot", ignoreCase = true) || msg.contains("captcha", ignoreCase = true) ||
                msg.contains("Sign in to confirm", ignoreCase = true) ||
                msg.contains("reCAPTCHA", ignoreCase = true) ->
                "YouTube blocked this video with a bot check, so its audio/subtitles could not be loaded. " +
                    "Try another video, or try again later."
            msg.contains("429", ignoreCase = true) || msg.contains("Too Many Requests", ignoreCase = true) ->
                "YouTube is rate-limiting requests (429). Wait a moment and try again."
            msg.contains("403", ignoreCase = true) ->
                "YouTube refused this video (403). It may be private, age-restricted or region-blocked."
            else ->
                "Could not load this video from YouTube: ${msg.ifBlank { e.javaClass.simpleName }}. Try again."
        }
    }

    /** Best audio stream: highest average bitrate. */
    fun bestAudioStream(streams: List<AudioStream>): AudioStream? =
        streams.maxByOrNull { it.averageBitrate }

    /** Video stream for a requested quality ("720p" default, "best", "1080p", ...). */
    fun videoStreamForQuality(streams: List<VideoStream>, quality: String?): VideoStream? {
        if (streams.isEmpty()) return null
        if (quality.equals("best", ignoreCase = true)) {
            return streams.maxByOrNull { resolutionHeight(it) }
        }
        val target = quality?.let { Regex("(\\d+)").find(it)?.groupValues?.get(1)?.toIntOrNull() } ?: 720
        streams.firstOrNull { resolutionHeight(it) == target }?.let { return it }
        // Highest stream at or below the target, else the lowest one available.
        return streams.filter { resolutionHeight(it) in 1..target }.maxByOrNull { resolutionHeight(it) }
            ?: streams.minByOrNull { resolutionHeight(it) }
    }

    private fun resolutionHeight(stream: VideoStream): Int =
        Regex("(\\d+)").find(stream.resolution ?: "")?.groupValues?.get(1)?.toIntOrNull() ?: 0

    fun audioExtension(format: MediaFormat?): String = when (format) {
        MediaFormat.M4A -> "m4a"
        MediaFormat.WEBMA, MediaFormat.WEBMA_OPUS -> "webm"
        MediaFormat.OPUS -> "opus"
        MediaFormat.MP3 -> "mp3"
        MediaFormat.OGG -> "ogg"
        else -> "m4a"
    }

    fun videoExtension(format: MediaFormat?): String = when (format) {
        MediaFormat.WEBM -> "webm"
        else -> "mp4"
    }

    /** Fetch small text (a subtitle file) over HTTP. */
    suspend fun fetchText(url: String): String = withContext(Dispatchers.IO) {
        val req = okhttp3.Request.Builder().url(url)
            .header("User-Agent", "Mozilla/5.0 (Android) ByokChat").build()
        try {
            Http.client.newCall(req).execute().use { resp ->
                if (!resp.isSuccessful) throw ToolException("Could not download the subtitles (HTTP ${resp.code}). Try again.")
                resp.body?.string().orEmpty()
            }
        } catch (e: IOException) {
            throw ToolException("Could not download the subtitles: ${e.message}. Try again.")
        }
    }

    /** Stream a media URL straight into an open output stream (no whole file in memory). */
    suspend fun downloadTo(url: String, out: OutputStream) = withContext(Dispatchers.IO) {
        val req = okhttp3.Request.Builder().url(url)
            .header("User-Agent", "Mozilla/5.0 (Android) ByokChat").build()
        try {
            Http.client.newCall(req).execute().use { resp ->
                if (!resp.isSuccessful) throw ToolException("Could not download the file (HTTP ${resp.code}). Try again.")
                val source = resp.body?.byteStream() ?: throw ToolException("The download returned no data. Try again.")
                source.use { input -> input.copyTo(out) }
            }
        } catch (e: IOException) {
            throw ToolException("Could not download the file: ${e.message}. Try again.")
        }
    }
}
