package com.example.byokchat.youtube

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class SubtitlesTest {

    private fun track(lang: String, auto: Boolean, url: String = "https://x/$lang") =
        SubtitleTrack(lang, auto, lang, url)

    @Test
    fun prefersManualInOriginalLanguageOverAutoAndViEn() {
        val tracks = listOf(track("vi", false), track("en", true), track("ja", false), track("ja", true))
        // No preference: manual in a non-vi/en language (the original) wins.
        assertEquals("ja", selectSubtitleTrack(tracks, null)?.languageTag)
        assertEquals(false, selectSubtitleTrack(tracks, null)?.isAutoGenerated)
    }

    @Test
    fun fallsBackToAutoInOriginalThenManualViEn() {
        assertEquals("ja", selectSubtitleTrack(listOf(track("vi", false), track("ja", true)), null)?.languageTag)
        assertEquals(true, selectSubtitleTrack(listOf(track("vi", false), track("ja", true)), null)?.isAutoGenerated)
        assertEquals("vi", selectSubtitleTrack(listOf(track("vi", false), track("en", false)), null)?.languageTag)
        assertEquals("en", selectSubtitleTrack(listOf(track("en", false)), null)?.languageTag)
        assertEquals("en", selectSubtitleTrack(listOf(track("en", true)), null)?.languageTag)
    }

    @Test
    fun preferredLanguageBeatsOriginalAndMatchesByPrefix() {
        val tracks = listOf(track("ja", false), track("en-US", true), track("vi", false))
        assertEquals("en-US", selectSubtitleTrack(tracks, "en")?.languageTag)
        assertEquals("vi", selectSubtitleTrack(tracks, "vi")?.languageTag)
        // A requested language with no track: fall back to the normal chain, not to nothing.
        assertEquals("ja", selectSubtitleTrack(tracks, "fr")?.languageTag)
    }

    @Test
    fun noTracksMeansNull() {
        assertNull(selectSubtitleTrack(emptyList(), null))
    }

    @Test
    fun subtitleFileSuffix() {
        assertEquals("en", subtitleFileSuffix(track("en-US", false)))
        assertEquals("ja-auto", subtitleFileSuffix(track("ja", true)))
    }

    @Test
    fun webVttToSrtConvertsCuesAndStripsMarkup() {
        val vtt = """
            WEBVTT
            Kind: captions
            Language: en

            00:00:01.000 --> 00:00:04.000
            Hello <b>world</b>

            00:00:05.500 --> 00:00:07.000 align:start
            Second &amp; line
            two lines
        """.trimIndent()
        assertEquals(
            "1\n00:00:01,000 --> 00:00:04,000\nHello world\n\n" +
                "2\n00:00:05,500 --> 00:00:07,000\nSecond & line\ntwo lines\n",
            webVttToSrt(vtt),
        )
    }

    @Test
    fun webVttToSrtSkipsNotesAndEmpty() {
        val vtt = "WEBVTT\n\nNOTE This is a note\n\n00:01:00.000 --> 00:01:02.000\nOnly cue\n"
        assertEquals("1\n00:01:00,000 --> 00:01:02,000\nOnly cue\n", webVttToSrt(vtt))
        assertEquals("", webVttToSrt("WEBVTT\n\n"))
    }
}
